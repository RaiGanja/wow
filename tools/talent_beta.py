def convert(cid):
    basis, trees = LAYOUTS[cid]
    old_p = os.path.join(HERE, 'content', 'talents', f'{cid}.json')
    old = json.load(open(old_p, encoding='utf-8')) if os.path.isfile(old_p) else {}
    kept = {t['id']: (t.get('icon'), t.get('iname')) for tr in old.get('trees', []) for t in tr['talents']}
    out = []
    for key, rows in zip(TREES[cid], trees):
        ids = {}
        talents = []
        for i, (r, c, m, name, spell, req, icon) in enumerate(sorted(rows, key=lambda x: (x[0], x[1])), 1):
            tid = f'{key}-{i}'
            ids[name] = tid
            x = {'id': tid, 'n': {'en': name}, 'r': r, 'c': c, 'm': m, 'spells': [spell] if spell else [], 'iname0': icon}
            talents.append((x, req))
        assert len({(x['r'], x['c']) for x, _ in talents}) == len(talents), (cid, key, 'two talents in one cell')
        res = []
        for x, req in talents:
            if req:
                x['req'] = ids[req]
            icon, iname = kept.get(x['id'], (None, None))
            if icon is not None and iname == x['iname0']:
                x['icon'], x['iname'] = icon, iname
            res.append(x)
        out.append({'key': key, 'talents': res})
    return {'class': cid, 'basis': basis, 'date': DATE, 'source': 'hand-copied layout (beta calculators / Classic), see tools/talent_beta.py',
            'trees': out, 'sprite': old.get('sprite', 0)}


def main():
    cids = sys.argv[1:] or list(LAYOUTS)
    os.makedirs(os.path.join(HERE, 'content', 'talents'), exist_ok=True)
    for cid in cids:
        d = convert(cid)
        p = os.path.join(HERE, 'content', 'talents', f'{cid}.json')
        json.dump(d, open(p, 'w', encoding='utf-8', newline='\n'), ensure_ascii=False, indent=1)
        print(f'{cid}: {sum(len(t["talents"]) for t in d["trees"])} talents ({d["basis"]}) -> {p}')


if __name__ == '__main__':
    main()
